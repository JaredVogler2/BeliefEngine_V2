/**
 * Lists the licence of every installed package straight from node_modules (no network, no third-party tool) and writes docs/THIRD_PARTY_LICENSES.md.
 * `--prod` limits it to what is bundled into the shipped page (react, react-dom and what they pull in).
 *   npx tsx scripts/licenses.ts [--prod] [--write]
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = process.cwd();
const prodOnly = process.argv.includes('--prod');
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')) as { dependencies?: Record<string, string>; devDependencies?: Record<string, string> };

function read(name: string, from: string): { dir: string; json: Record<string, unknown> } | null {
  // walk up like Node's resolver: nested node_modules first, then the project's
  let dir = from;
  for (;;) {
    const p = join(dir, 'node_modules', name, 'package.json');
    if (existsSync(p)) return { dir: join(dir, 'node_modules', name), json: JSON.parse(readFileSync(p, 'utf8')) as Record<string, unknown> };
    const up = join(dir, '..');
    if (up === dir || dir.length <= root.length - 1) break;
    dir = up;
  }
  const p = join(root, 'node_modules', name, 'package.json');
  return existsSync(p) ? { dir: join(root, 'node_modules', name), json: JSON.parse(readFileSync(p, 'utf8')) as Record<string, unknown> } : null;
}

const seen = new Map<string, { version: string; license: string }>();
function walk(name: string, from: string, optional: boolean): void {
  const r = read(name, from);
  if (!r) {
    if (!optional) console.error(`not installed: ${name}`);
    return;
  }
  const version = String(r.json.version);
  const key = `${name}@${version}`;
  if (seen.has(key)) return;
  const lic = r.json.license ?? (Array.isArray(r.json.licenses) ? (r.json.licenses as { type: string }[]).map((l) => l.type).join(' OR ') : 'UNKNOWN');
  seen.set(key, { version, license: typeof lic === 'string' ? lic : JSON.stringify(lic) });
  const deps = { ...(r.json.dependencies as Record<string, string> | undefined) };
  for (const d of Object.keys(deps)) walk(d, r.dir, false);
  for (const d of Object.keys((r.json.optionalDependencies as Record<string, string> | undefined) ?? {})) walk(d, r.dir, true);
}
for (const d of Object.keys(pkg.dependencies ?? {})) walk(d, root, false);
if (!prodOnly) for (const d of Object.keys(pkg.devDependencies ?? {})) walk(d, root, false);

const byLicense = new Map<string, number>();
for (const v of seen.values()) byLicense.set(v.license, (byLicense.get(v.license) ?? 0) + 1);
const lines = [...seen.entries()].sort((a, b) => (a[0] < b[0] ? -1 : 1));
console.log(`${seen.size} packages${prodOnly ? ' (production)' : ''}:`, [...byLicense.entries()].sort((a, b) => b[1] - a[1]).map(([l, n]) => `${l} x${n}`).join(', '));
const copyleft = lines.filter(([, v]) => /GPL|AGPL|LGPL|SSPL|UNKNOWN|UNLICENSED|BUSL|CC-BY-NC/i.test(v.license));
if (copyleft.length) console.log('needs a look:', copyleft.map(([k, v]) => `${k} (${v.license})`).join(', '));
if (process.argv.includes('--write')) {
  const md = ['# Third-party licences', '', `Generated by \`npx tsx scripts/licenses.ts${prodOnly ? ' --prod' : ''} --write\` from the installed packages (no network). ${seen.size} packages${prodOnly ? ' reachable from the shipped page' : ' including development tools, none of which is shipped to players'}.`, '', '| Licence | Packages |', '| --- | ---: |', ...[...byLicense.entries()].sort((a, b) => b[1] - a[1]).map(([l, n]) => `| ${l} | ${n} |`), '', copyleft.length ? `**Needs a look:** ${copyleft.map(([k, v]) => `${k} (${v.license})`).join(', ')}` : 'No copyleft, unknown or non-commercial licences.', '', '<details><summary>Every package</summary>', '', ...lines.map(([k, v]) => `* ${k}: ${v.license}`), '', '</details>', ''].join('\n');
  writeFileSync(join(root, prodOnly ? 'docs/THIRD_PARTY_LICENSES_PROD.md' : 'docs/THIRD_PARTY_LICENSES.md'), md);
}
