/*
 * A scripted MCP client session for docs/MCP_V2.md: npx tsx scripts/mcp-v2-session.ts > docs/data/mcp/v2-hens-session.md
 *
 * The real server process over stdio (official SDK client), replaying the recorded "hens" chain (tests/fixtures/v2-bridge-traces.json)
 * with propose_belief / confirm_belief in place of the browser's composer. A script, not a model: it shows what an agent sees.
 */
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StdioClientTransport } from '@modelcontextprotocol/sdk/client/stdio.js';
import type { Action, CreateRunOptions } from '../src/engine/index.ts';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const fx = JSON.parse(readFileSync(join(ROOT, 'tests/fixtures/v2-bridge-traces.json'), 'utf8')) as Record<string, { opts: CreateRunOptions; sentence: string; stateHash: string; actions: Action[] }>;
const t = fx.hens;

// eslint-disable-next-line @typescript-eslint/no-explicit-any
type J = Record<string, any>;
const out: string[] = [];
const say = (s = '') => out.push(s);

const transport = new StdioClientTransport({ command: process.execPath, args: ['--import', 'tsx', join(ROOT, 'mcp/server.ts')], cwd: ROOT, env: { ...(process.env as Record<string, string>), BELIEF_ENGINE_HOME: ':memory:', BE_AI_ENABLED: '' }, stderr: 'pipe' });
const client = new Client({ name: 'mcp-v2-session-script', version: '1.0.0' });
await client.connect(transport);
const call = async (name: string, args: J = {}): Promise<{ text: string; data: J; isError: boolean }> => {
  const r = (await client.callTool({ name, arguments: args })) as { isError?: boolean; structuredContent?: J; content: { text?: string }[] };
  return { text: r.content[0]?.text ?? '', data: r.structuredContent ?? {}, isError: !!r.isError };
};

say('# A scripted MCP session in a Generative Reality run');
say();
say(`Generated by \`npx tsx scripts/mcp-v2-session.ts\`: the real server over stdio, the official SDK client, no model. It replays the recorded "hens" chain (${t.actions.length} actions) with \`propose_belief\` and \`confirm_belief\` where the browser used its composer.`);
say();
const g = await call('create_game', { scenarioId: t.opts.scenarioId, seed: t.opts.seed, difficulty: t.opts.difficulty, variant: 'generative' });
const runId = g.data.runId as string;
let rev = g.data.revision as number;
say(`**create_game** \`{ scenarioId: "${t.opts.scenarioId}", seed: ${t.opts.seed}, variant: "generative" }\` → ${g.text}`);
say();
for (const a of t.actions) {
  if (a.type === 'COMPOSE') {
    const p = await call('propose_belief', { runId, text: t.sentence });
    const c = p.data.interpretations[0];
    say(`**propose_belief** \`"${t.sentence}"\` → ${p.text}`);
    say();
    say('```json');
    say(JSON.stringify({ kind: p.data.kind, title: c.title, rating: c.rating, confidence: c.confidence, said: c.said, willDo: c.willDo, requires: c.requires, support: c.support, upkeep: c.upkeep, sideEffects: c.sideEffects, whoMayPushBack: c.whoMayPushBack, leftOut: c.leftOut, cost: c.cost, demonstratedAt: c.demonstratedAt, needsAcknowledgement: c.needsAcknowledgement }, null, 2));
    say('```');
    say();
    const d = await call('confirm_belief', { runId, token: c.token, expectedRevision: rev, idempotencyKey: `compose-${rev}` });
    rev = d.data.revision;
    say(`**confirm_belief** → ${d.text} (claim \`${d.data.claim.id}\`, ${d.data.remainingInfluence} Influence left)`);
    say();
    continue;
  }
  if (a.type === 'END_DAY') {
    const n = await call('end_day', { runId, expectedRevision: rev, idempotencyKey: `night-${rev}` });
    rev = n.data.revision;
    const notable = n.data.importantEvents.filter((e: J) => /^(LAW_|CHICKENS_ROSE|DEATH|HOME_FLOODED|BELIEVER_GAINED)/.test(e.code)).slice(0, 6).map((e: J) => `${e.code}: ${e.text}`);
    say();
    say(`**end_day** (day ${n.data.day}) → ${n.text}`);
    for (const l of notable) say(`- ${l}`);
    say();
    continue;
  }
  const r = await call('take_action', { runId, action: a, expectedRevision: rev, idempotencyKey: `act-${rev}` });
  if (r.isError) throw new Error(r.text);
  rev = r.data.revision;
  say(`- **take_action** \`${JSON.stringify(a)}\` → ${r.text}`);
}
say();
const res = await call('get_results', { runId });
say(`**get_results** → ${res.text}`);
say();
say(`State hash \`${res.data.verification.stateHash}\`; the browser's recorded hash for the same chain is \`${t.stateHash}\` (${res.data.verification.stateHash === t.stateHash ? 'identical' : 'DIFFERENT'}).`);
await client.close();
process.stdout.write(out.join('\n') + '\n');
